// Builds docs/llms-full.txt: one file with the user and agent docs, for agents with small context windows
// or tools that ingest a single document. Run: node scripts/build-llms.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(import.meta.url), '..', '..');
const sources = [
  'AGENTS.md',
  'docs/agents/conventions.md',
  ...walk(join(root, 'docs/users')),
  'docs/humans/architecture.md',
  'docs/humans/status.md',
];

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.md') ? [relative(root, p)] : [];
  });
}

const parts = [
  '# Kvui UI: full documentation for AI agents',
  '',
  'Generated by scripts/build-llms.mjs. Do not edit. Source files are listed at the top of each section.',
  'Component names, props, events and methods must match packages/core/dist-docs/API.md.',
  '',
];
for (const rel of sources) {
  const body = readFileSync(join(root, rel), 'utf8').replace(/\(\.\.?\/[^)]*\)/g, (m) => m); // links kept as written
  parts.push(`\n\n==== SOURCE: ${rel} ====\n`, body.trim());
}
parts.push('\n\n==== SOURCE: packages/core/dist-docs/API.md (excerpt: component list) ====\n');
const api = readFileSync(join(root, 'packages/core/dist-docs/API.md'), 'utf8');
parts.push(api.split('\n').filter((l) => l.startsWith('## ')).join('\n'));

writeFileSync(join(root, 'docs/llms-full.txt'), parts.join('\n') + '\n');
console.log(`llms-full.txt: ${sources.length} source files, ${Math.round(parts.join('\n').length / 1024)} KB`);
