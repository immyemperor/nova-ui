// Snapshot of everything the component explorers need, so no app imports files outside its own build.
//   node apps/shared/scripts/snapshot.mjs           (run by each app before dev and build)
// Writes:
//   apps/shared/generated/library.ts                 React apps: component API, example source, Material names
//   apps/playground-angular/src/app/explorer/library-data.ts   Angular: the same, for its own examples
// Copies packages/css/dist/icons.css to public/nova-icons.css of every app (when it has been built).
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const apps = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const repo = join(apps, '..');
const read = (p) => readFileSync(p, 'utf8');

const manifest = JSON.parse(read(join(repo, 'packages/core/dist-docs/custom-elements.json')));
const DECLARATIONS = manifest.modules.flatMap((m) => m.declarations);

/** Imports (the header of an examples file) plus each "// @example <tag>" block, ready to copy. */
export function extractExamples(text) {
  const header = text.slice(0, Math.max(0, text.indexOf('// @example'))).trimEnd();
  const out = {};
  for (const m of text.matchAll(/\/\/ @example (ui-[\w-]+)\n([\s\S]*?)\/\/ @end/g)) {
    out[m[1]] = `${header}\n\n${m[2].replace(/\n+$/, '')}\n`;
  }
  return out;
}

const materialPath = join(repo, 'packages/css/src/generated/material-icon-names.json');
const MATERIAL = existsSync(materialPath) ? JSON.parse(read(materialPath)) : [];

const reactExamples = extractExamples(read(join(apps, 'shared/react/explorer/examples.tsx')));
const angularExamplesPath = join(apps, 'playground-angular/src/app/explorer/examples.ts');
const angularExamples = existsSync(angularExamplesPath) ? extractExamples(read(angularExamplesPath)) : {};

const json = (v) => JSON.stringify(v, null, 2);
writeFileSync(join(apps, 'shared/generated/library.ts'),
`// GENERATED by apps/shared/scripts/snapshot.mjs. Do not edit.
export const DECLARATIONS: unknown[] = ${json(DECLARATIONS)};
export const REACT_EXAMPLE_SOURCES: Record<string, string> = ${json(reactExamples)};
export const MATERIAL_NAMES: readonly string[] = ${json(MATERIAL)};
`);

const angularDir = join(apps, 'playground-angular/src/app/explorer');
mkdirSync(angularDir, { recursive: true });
writeFileSync(join(angularDir, 'library-data.ts'),
`// GENERATED by apps/shared/scripts/snapshot.mjs. Do not edit.
export const DECLARATIONS: unknown[] = ${json(DECLARATIONS)};
export const ANGULAR_EXAMPLE_SOURCES: Record<string, string> = ${json(angularExamples)};
export const MATERIAL_NAMES: readonly string[] = ${json(MATERIAL)};
`);

// The category list is plain TypeScript, so Angular gets a copy of it.
copyFileSync(join(apps, 'shared/react/explorer/catalog.ts'), join(angularDir, 'catalog.ts'));


const copied = [];
const iconsDist = join(repo, 'packages/css/dist');
const iconFiles = [
  ['icons.css', 'nova-icons.css'],
  ['material-symbols-outlined.woff2', 'material-symbols-outlined.woff2'],
];
for (const app of ['playground-vite', 'playground-react', 'playground-next', 'playground-angular']) {
  let any = false;
  for (const [from, to] of iconFiles) {
    if (!existsSync(join(iconsDist, from))) continue;
    mkdirSync(join(apps, app, 'public'), { recursive: true });
    copyFileSync(join(iconsDist, from), join(apps, app, 'public', to));
    any = true;
  }
  if (any) copied.push(app);
}
console.log(copied.length
  ? `icons copied to ${copied.length} apps`
  : 'icons not built yet: run pnpm --filter @omni/css icons:update and build');