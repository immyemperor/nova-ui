// Writes src/app/source.ts with the text of each demo file, so the app can show and copy its own code.
// Runs before start and build (see package.json). Angular CLI has no ?raw imports, so this is the equivalent.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = ['src/app/catalogue/catalogue.component.ts', 'src/app/code-block.component.ts', 'src/styles.css'];
const entries = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(root, f), 'utf8'))},`);
writeFileSync(join(root, 'src/app/source.ts'),
  `// GENERATED by scripts/snapshot.mjs. Do not edit.\nexport const SOURCES: Record<string, string> = {\n${entries.join('\n')}\n};\n`);
console.log(`snapshot: ${files.length} files`);
