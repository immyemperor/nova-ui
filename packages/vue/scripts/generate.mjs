// Generates Vue 3 wrappers for every Nova component from the docs manifest. Run: node scripts/generate.mjs
// Props map to Vue props; events map to emitted events (uiChange -> 'ui-change' listeners via onUiChange).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(join(root, '..', 'core', 'dist-docs', 'custom-elements.json'), 'utf8'));
const decls = manifest.modules.flatMap((m) => m.declarations).sort((a, b) => a.tagName.localeCompare(b.tagName));

const pascal = (tag) => tag.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const camel = (s) => s.replace(/-([a-z])/g, (_m, c) => c.toUpperCase());
const propCamel = (s) => camel(s);
const vueType = (t) => {
  if (t === 'boolean') return 'Boolean';
  if (t === 'number') return 'Number';
  if (t === 'string' || /^'[^']+'/.test(t)) return 'String';
  return '[Object, Array, Function]';
};

const blocks = decls.map((d) => {
  const props = d.attributes.map((a) => `    ${propCamel(a.name)}: { type: ${vueType(a.type.text)}, default: undefined },`).join('\n');
  const emits = d.events.map((e) => `'${camel(e.name)}'`);
  const handlers = d.events.map((e) => { const ev = camel(e.name); return `      on${ev[0].toUpperCase()}${ev.slice(1)}: (ev: CustomEvent) => emit('${ev}', ev.detail),`; }).join('\n');
  const attrs = d.attributes.map((a) => `        '${a.name}': props.${propCamel(a.name)} as any,`).join('\n');
  return `/** ${(d.description || d.tagName).replace(/\*\//g, '* /')} */
export const ${pascal(d.tagName)} = defineComponent({
  name: '${pascal(d.tagName)}',
  inheritAttrs: true,
  props: {
${props}
  },
  emits: [${emits.join(', ')}],
  setup(props, { slots, emit }) {
    return () => h('${d.tagName}', {
${attrs}
${handlers}
    }, slots.default?.());
  },
});`;
});

const header = `// GENERATED by packages/vue/scripts/generate.mjs from core/dist-docs/custom-elements.json. Do not edit.
import { defineComponent, h } from 'vue';
`;
mkdirSync(join(root, 'src'), { recursive: true });
writeFileSync(join(root, 'src', 'components.ts'), header + '\n' + blocks.join('\n\n') + '\n');
writeFileSync(join(root, 'src', 'index.ts'), `export * from './components';\n`);
console.log(`vue: ${decls.length} wrappers generated`);
