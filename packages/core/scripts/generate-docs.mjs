// Builds API docs and editor data straight from the component sources. No build needed. Run: node scripts/generate-docs.mjs
// Outputs (in dist-docs/):
//   custom-elements.json  machine-readable manifest (tags, attributes, properties, events, methods, slots)
//   vscode-html-data.json VS Code / JetBrains custom data: autocomplete and hover for every <ui-*> tag
//   API.md                human-readable reference
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const compDir = join(root, 'src', 'components');
const outDir = join(root, 'dist-docs');

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const doc = (block) => (block ? block.replace(/\/\*\*|\*\/|^\s*\*\s?/gm, '').replace(/\s+/g, ' ').trim() : '');

/** Read the doc comment immediately before index `at` in `src`. */
function docBefore(src, at) {
  const head = src.slice(0, at);
  // The last doc comment before `at`, with no other comment in between (so it can't reach back to the class doc).
  const m = /\/\*\*(?:(?!\*\/)[\s\S])*\*\/\s*$/.exec(head);
  return m ? doc(m[0]) : '';
}

function typeToAttr(type, aliases = {}, fallback) {
  let t = (type ?? '').trim();
  if (!t && fallback !== undefined) {
    if (fallback === 'true' || fallback === 'false') t = 'boolean';
    else if (/^-?[\d.]+$/.test(fallback)) t = 'number';
    else if (/^['"]/.test(fallback)) t = 'string';
  }
  if (aliases[t]) t = aliases[t]; // resolve `type ButtonVariant = 'primary' | ...`
  const union = [...t.matchAll(/'([^']+)'/g)].map((m) => m[1]);
  if (union.length && /^'[^']+'(\s*\|\s*'[^']+')*$/.test(t)) return { kind: 'enum', values: union, type: t };
  if (t === 'boolean') return { kind: 'boolean', type: t };
  if (t === 'number') return { kind: 'number', type: t };
  if (t === 'string') return { kind: 'string', type: t };
  return { kind: 'complex', type: t || 'any' };
}

function parseComponent(file) {
  const src = readFileSync(file, 'utf8');
  const tagM = /tag:\s*'([^']+)'/.exec(src);
  if (!tagM) return null;
  const className = /export class (\w+)/.exec(src)?.[1] ?? tagM[1];
  const aliases = Object.fromEntries([...src.matchAll(/type\s+(\w+)\s*=\s*((?:'[^']+'\s*\|?\s*)+);/g)].map((m) => [m[1], m[2].trim()]));
  const props = [];
  const propRe = /@Prop\(([^)]*)\)\s+(\w+)([!?])?(?:\s*:\s*([^=;\n]+?))?\s*(?:=\s*([^;\n]+))?;/g;
  for (const m of src.matchAll(propRe)) {
    const info = typeToAttr(m[4], aliases, m[5]?.trim());
    props.push({
      name: m[2],
      attribute: kebab(m[2]),
      default: m[5]?.trim(),
      description: docBefore(src, m.index),
      ...info,
      reflects: /reflect:\s*true/.test(m[1]),
    });
  }
  const events = [];
  // Payload may contain ';' (object types), so read to the closing '>;' at the end of the declaration.
  for (const m of src.matchAll(/@Event\([^)]*\)\s+(\w+)!?:\s*EventEmitter<(.*?)>;[ \t]*$/gm)) {
    events.push({ name: m[1], detail: m[2].trim(), description: docBefore(src, m.index) });
  }
  const methods = [];
  for (const m of src.matchAll(/@Method\(\)\s*(?:async\s+)?(\w+)\s*\(([^)]*)\)/g)) {
    methods.push({ name: m[1], params: m[2].trim(), description: docBefore(src, m.index) });
  }
  const slots = [...new Set([...src.matchAll(/<slot(?:\s+name="([^"]+)")?/g)].map((m) => m[1] ?? 'default'))];
  const classDoc = docBefore(src, src.indexOf('export class'));
  return { tag: tagM[1], className, description: classDoc, props, events, methods, slots, file: file.replace(root + '/', '') };
}

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.tsx') ? [p] : [];
  });
}

// Scan core and the optional editor package, so every shipped tag is documented.
const editorDir = join(root, '..', 'editor', 'src', 'components');
const components = [...walk(compDir), ...walk(editorDir)].map(parseComponent).filter(Boolean).sort((a, b) => a.tag.localeCompare(b.tag));
mkdirSync(outDir, { recursive: true });

// 1. Custom Elements Manifest (subset of the standard schema)
const manifest = {
  schemaVersion: '1.0.0',
  readme: 'Generated by scripts/generate-docs.mjs. Do not edit.',
  modules: components.map((c) => ({
    kind: 'javascript-module',
    path: c.file,
    declarations: [{
      kind: 'class',
      name: c.className,
      tagName: c.tag,
      description: c.description,
      attributes: c.props.map((p) => ({ name: p.attribute, type: { text: p.type }, default: p.default, description: p.description })),
      members: c.props.map((p) => ({ kind: 'field', name: p.name, type: { text: p.type }, default: p.default, description: p.description })),
      events: c.events.map((e) => ({ name: kebab(e.name), type: { text: e.detail }, description: e.description })),
      methods: c.methods.map((m) => ({ kind: 'method', name: m.name, parameters: m.params, description: m.description })),
      slots: c.slots.map((s) => ({ name: s === 'default' ? '' : s })),
    }],
  })),
};
writeFileSync(join(outDir, 'custom-elements.json'), JSON.stringify(manifest, null, 2) + '\n');

// 2. VS Code / JetBrains custom HTML data (autocomplete, hover docs, enum values)
const vscode = {
  version: 1.1,
  tags: components.map((c) => ({
    name: c.tag,
    description: c.description || `Nova ${c.className}`,
    attributes: [
      ...c.props.map((p) => ({
        name: p.attribute,
        description: `${p.description}${p.default ? ` (default: ${p.default})` : ''}`.trim(),
        ...(p.kind === 'enum' ? { values: p.values.map((v) => ({ name: v })) } : {}),
        ...(p.kind === 'boolean' ? { valueSet: 'v' } : {}),
      })),
      ...c.events.map((e) => ({ name: `on${e.name[0].toUpperCase()}${e.name.slice(1)}`, description: `Event: ${e.description || e.name}. Detail: ${e.detail}` })),
    ],
  })),
  valueSets: [{ name: 'v', values: [{ name: 'true' }, { name: 'false' }] }],
};
writeFileSync(join(outDir, 'vscode-html-data.json'), JSON.stringify(vscode, null, 2) + '\n');

// 3. Human-readable reference
const md = [
  '# Nova UI component reference',
  '',
  `Generated from ${components.length} component sources. Regenerate with \`node scripts/generate-docs.mjs\`.`,
  '',
];
for (const c of components) {
  md.push(`## \`<${c.tag}>\``, '', c.description || '', '');
  if (c.props.length) {
    md.push('| Attribute | Type | Default | Description |', '| --- | --- | --- | --- |');
    for (const p of c.props) md.push(`| \`${p.attribute}\` | \`${p.type}\` | ${p.default ? `\`${p.default}\`` : ''} | ${p.description.replace(/\|/g, '\\|')} |`);
    md.push('');
  }
  if (c.events.length) {
    md.push('**Events**', '');
    for (const e of c.events) md.push(`- \`${e.name}\` (detail: \`${e.detail}\`). ${e.description}`);
    md.push('');
  }
  if (c.methods.length) {
    md.push('**Methods**', '');
    for (const m of c.methods) md.push(`- \`${m.name}(${m.params})\`. ${m.description}`);
    md.push('');
  }
  if (c.slots.length) md.push(`**Slots:** ${c.slots.map((s) => (s === 'default' ? 'default' : `\`${s}\``)).join(', ')}`, '');
}
writeFileSync(join(outDir, 'API.md'), md.join('\n') + '\n');

console.log(`docs: ${components.length} components, ${components.reduce((n, c) => n + c.props.length, 0)} props, ${components.reduce((n, c) => n + c.events.length, 0)} events, ${components.reduce((n, c) => n + c.methods.length, 0)} methods`);
export { components };
